"""Generate docs/fields.md from the schemas' description, x-unit and examples keywords.

Run `python scripts/field_reference.py --write` after a schema edit; without --write it fails when
the page is stale.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
PAGE = "docs/fields.md"
SECTIONS = (
    ("Methodology document (`schemas/methodology.schema.json`)", "schemas/methodology.schema.json"),
    ("Canonical names table (`names/names.yaml`)", "schemas/names.schema.json"),
    ("Run manifest (`schemas/run.schema.json`)", "schemas/run.schema.json"),
    ("Measurement (`schemas/measurement.schema.json`)", "schemas/measurement.schema.json"),
    ("Aggregate (`schemas/aggregate.schema.json`)", "schemas/aggregate.schema.json"),
)


def _resolve(schema: dict[str, Any], node: dict[str, Any]) -> dict[str, Any]:
    """Follow local $refs; keywords beside a $ref (such as its description) win."""
    while "$ref" in node:
        target: Any = schema
        for part in node["$ref"].removeprefix("#/").split("/"):
            target = target[part]
        node = {**target, **{key: value for key, value in node.items() if key != "$ref"}}
    return node


def _rows(schema: dict[str, Any], node: dict[str, Any], prefix: str) -> list[str]:
    node = _resolve(schema, node)
    properties = dict(node.get("properties", {}))
    for alternative in node.get("oneOf", []) + node.get("anyOf", []):
        for key, value in _resolve(schema, alternative).get("properties", {}).items():
            properties.setdefault(key, value)
    rows = []
    for key, value in properties.items():
        child = _resolve(schema, value)
        path = f"{prefix}{key}"
        items = child.get("items")
        if isinstance(items, dict):
            path += "[]"
        if "description" in child:
            unit = child.get("x-unit", "")
            examples = child.get("examples")
            example = f"`{json.dumps(examples[0], ensure_ascii=False)}`" if examples else ""
            rows.append(f"| `{path}` | {child['description']} | {unit} | {example} |")
        rows.extend(_rows(schema, items if isinstance(items, dict) else child, f"{path}."))
    return rows


def page_text(root: Path = ROOT) -> str:
    """Return the field reference page for the schemas under root."""
    lines = [
        "<!-- Generated by python scripts/field_reference.py --write; do not edit. -->",
        "# Field reference",
        "",
        "One row per described property of the methodology schemas and canonical names table, "
        "generated from each property's `description`, `x-unit` and `examples` in the schema. "
        "Units are those of the value; blank means the field has no unit. Methodology fields may "
        "also hold `unknown` where marked in the schema; see the schema for the exact types.",
    ]
    for title, source in SECTIONS:
        schema = json.loads((root / source).read_text(encoding="utf-8"))
        lines += [
            "",
            f"## {title}",
            "",
            "| Property | Meaning | Unit | Example |",
            "| --- | --- | --- | --- |",
        ]
        lines += _rows(schema, schema, "")
    return "\n".join(lines) + "\n"


def main() -> None:
    """Write the page, or fail when the checked-in page differs from the schemas."""
    parser = argparse.ArgumentParser()
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args()
    page = ROOT / PAGE
    expected = page_text()
    if args.write:
        page.write_text(expected, encoding="utf-8")
    elif page.read_text(encoding="utf-8") != expected:
        raise SystemExit(f"{PAGE} is stale; run python scripts/field_reference.py --write")


if __name__ == "__main__":
    main()
