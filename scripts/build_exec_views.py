"""Build the two Exec Latency reader documents from their one source.

sources/exec-latency-views.yaml states what both views share once, and each view's differences.
Run this after editing it; tests/test_exec_views.py fails when the committed output is stale.
"""

from __future__ import annotations

import copy
import shutil
from pathlib import Path
from typing import Any

import yaml

from sandbox_benchmark_verifier.yaml_load import load_yaml

ROOT = Path(__file__).resolve().parents[1]
# Both paths are relative to a repository root.
SOURCE = Path("sources/exec-latency-views.yaml")
OUTPUT = Path("methodology/03-sandbox-operations/exec-views.yaml")
SCHEMA = "# yaml-language-server: $schema=../../schemas/methodology.schema.json"
HEADER = (
    "# Generated by scripts/build_exec_views.py from sources/exec-latency-views.yaml.\n"
    "# Do not edit.\n"
)
ORDER = [
    "id",
    "version",
    "effective",
    "name",
    "category",
    "notes",
    "inherits",
    "metrics",
    "environment",
    "clocks",
    "procedure",
    "timing_boundaries",
    "statistics",
    "cost",
    "failure_policy",
    "independence_answers",
    "parameters",
    "interpretation",
    "validity_checks",
    "source",
    "execution",
]


def merge(base: dict[str, Any], over: dict[str, Any]) -> dict[str, Any]:
    """Deep-merge mappings; anything else in `over` replaces what `base` has."""
    merged = copy.deepcopy(base)
    for key, value in over.items():
        if isinstance(value, dict) and isinstance(merged.get(key), dict):
            merged[key] = merge(merged[key], value)
        else:
            merged[key] = copy.deepcopy(value)
    return merged


def documents(source: dict[str, Any]) -> list[dict[str, Any]]:
    """One document per view: the shared fields with the view's own fields over them."""
    built = []
    for view in source["views"].values():
        document = merge(source["shared"], view)
        document["parameters"] = {
            **document["parameters"],
            "path": f"parameters/{document['id']}/{document['version']}/",
        }
        unknown = set(document) - set(ORDER)
        if unknown:
            raise ValueError(f"fields without a place in the document order: {sorted(unknown)}")
        built.append({key: document[key] for key in ORDER if key in document})
    return built


def render(source: dict[str, Any]) -> str:
    """The generated file's text."""
    parts = [
        yaml.safe_dump(document, sort_keys=False, width=100, allow_unicode=True)
        for document in documents(source)
    ]
    return f"{HEADER}{SCHEMA}\n" + "\n---\n".join(parts)


def write_parameters(source: dict[str, Any], root: Path = ROOT) -> None:
    """Give each document its own parameters directory, a copy of the shared one."""
    shared = root / source["shared"]["parameters"]["path"]
    for document in documents(source):
        target = root / document["parameters"]["path"]
        shutil.copytree(shared, target, dirs_exist_ok=True)


def main(root: Path = ROOT) -> None:
    """Write the generated file and the parameters directories."""
    source = load_yaml((root / SOURCE).read_text(encoding="utf-8"))
    write_parameters(source, root)
    (root / OUTPUT).write_text(render(source), encoding="utf-8")


if __name__ == "__main__":
    main()
